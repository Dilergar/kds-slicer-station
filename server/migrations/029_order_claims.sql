-- ============================================================================
-- Миграция 029: Общий клейм карточки «В работе» + автор порции в истории
-- Дата: 2026-08-15
--
-- Проблема:
--   Тап по карточке помечал её «В работе» (лаймовая рамка + 🔪), но метка
--   жила ТОЛЬКО в локальном стейте SlicerStation одного браузера. Пока за
--   доской стоял один нарезчик — этого хватало. При работе вдвоём-втроём с
--   разных планшетов метка не значила ничего: второй нарезчик не видел, что
--   блюдо уже кто-то взял, и резал его повторно.
--
-- Решение:
--   Клейм переезжает в теневую таблицу slicer_order_state — ту же, где живут
--   статус, парковка и merge_ack, — и раздаётся всем планшетам обычным
--   GET /api/orders (поллинг 4 сек). Личность берётся из PIN-сессии
--   (users.uuid + users.login), поэтому на карточке видно КОНКРЕТНОГО
--   человека, а не «занято».
--
--   * claimed_by_uuid / claimed_by_name — кто держит карточку. NULL = свободна.
--     Имя денормализовано намеренно: users — чужая таблица, JOIN к ней на
--     каждый поллинг каждого планшета не нужен, а сотрудника могут удалить
--     (тогда на карточке останется имя, под которым её реально взяли).
--   * claimed_at — когда взяли. Нужен для детерминизма при спорах и для
--     возможной будущей авто-очистки зависших клеймов (сейчас по решению
--     владельца клейм висит до «Готово»).
--
-- Жизненный цикл клейма (см. server/src/routes/orders.ts):
--   * ставится/снимается POST /api/orders/claim и /api/orders/unclaim;
--   * снять чужой клейм нельзя — только владелец;
--   * «Готово» / «Частично» на чужой карточке разрешены, но UI спрашивает
--     подтверждение («её взял Азамат, всё равно закрыть?»);
--   * ПАРКОВКА снимает клейм (заказ отложен, человек переключился на другое);
--   * РАЗМОРОЗКА клейм сохраняет (взял рыбу — доделаю её же после разморозки);
--   * /restore из истории сбрасывает — восстановленная позиция «чистый лист».
--
-- Автор порции в отчётах:
--   slicer_order_history.completed_by_uuid / completed_by_name — кто нажал
--   «Готово» или «Частично». Именно нажавший, а не державший клейм: это
--   единственное действие, которое точно было (решение владельца). Старые
--   записи остаются с NULL → в отчёте показываются как «—».
-- ============================================================================

ALTER TABLE slicer_order_state
  ADD COLUMN IF NOT EXISTS claimed_by_uuid VARCHAR(255),
  ADD COLUMN IF NOT EXISTS claimed_by_name VARCHAR(255),
  ADD COLUMN IF NOT EXISTS claimed_at TIMESTAMPTZ;

COMMENT ON COLUMN slicer_order_state.claimed_by_uuid IS
  'users.uuid нарезчика, который взял позицию в работу (тап по карточке). '
  'NULL = позиция свободна. Виден всем планшетам через GET /api/orders.';
COMMENT ON COLUMN slicer_order_state.claimed_by_name IS
  'users.login нарезчика на момент клейма (денормализовано: чужую таблицу '
  'users не джойним на каждый поллинг, а сотрудника могут удалить).';
COMMENT ON COLUMN slicer_order_state.claimed_at IS
  'Когда позицию взяли в работу. Тайбрейкер при споре двух клеймов на одну '
  'склеенную карточку и точка опоры для будущей авто-очистки зависших.';

ALTER TABLE slicer_order_history
  ADD COLUMN IF NOT EXISTS completed_by_uuid VARCHAR(255),
  ADD COLUMN IF NOT EXISTS completed_by_name VARCHAR(255);

COMMENT ON COLUMN slicer_order_history.completed_by_uuid IS
  'users.uuid того, кто нажал «Готово»/«Частично». NULL для записей, '
  'сделанных до миграции 029 или без активной сессии.';
COMMENT ON COLUMN slicer_order_history.completed_by_name IS
  'users.login автора порции на момент завершения — показывается в отчёте '
  '«Скорость нарезчика» и участвует в фильтре по нарезчикам.';

-- Отчёты фильтруют историю по автору внутри выбранного периода, поэтому
-- индекс составной: сначала автор, потом время. Частичный (WHERE NOT NULL) —
-- у накопленных до миграции записей автора нет, держать их в индексе незачем.
CREATE INDEX IF NOT EXISTS idx_slicer_order_history_completed_by
  ON slicer_order_history(completed_by_uuid, completed_at)
  WHERE completed_by_uuid IS NOT NULL;
