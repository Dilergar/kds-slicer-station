-- ============================================================================
-- Миграция 030: столы-домики — кирпичная метка номера стола на карточке
-- Дата: 2026-08-15
--
-- Проблема:
--   Часть посадки ресторана — отдельные домики (столы 30, 31, 32). Блюда для
--   них уносят не в общий зал, а на улицу, и нарезчику важно видеть это ещё
--   при нарезке — по номеру стола на карточке. На доске все номера выглядят
--   одинаково (жёлтые), домик от обычного стола не отличить.
--
-- Решение:
--   Список «особых» номеров хранится в настройках модуля и правится в UI
--   (Админка → Общие Настройки → «Столы-домики»), без правок кода при
--   изменении рассадки. Номер такого стола рисуется на карточке кирпичным
--   цветом в рамке в форме домика (OrderCard, `столы:`).
--
--   Почему массив в настройках, а не таблица: это ровно список чисел без
--   собственных атрибутов, живёт вместе с остальными тумблерами доски и
--   читается тем же GET /api/settings, который фронт и так грузит при старте.
--
-- DEFAULT '{30,31,32}' — боевая рассадка ресторана на дату миграции. Так
-- модуль работает «из коробки» и на чистой установке, и после восстановления
-- дампа данных (в COPY slicer_settings этой колонки нет — подставится DEFAULT).
-- Значение не является частью логики: любой номер добавляется/убирается в UI.
--
-- ⚠️ Фиолетовая рамка вокруг номера НЕ трогается — это другой смысл
-- («стол парковался в течение смены», OrderCard). Если стол одновременно
-- домик и паркованный — домик даёт форму и обводку, парковка остаётся
-- фиолетовой заливкой и цветом цифры внутри него.
-- ============================================================================

ALTER TABLE slicer_settings
  ADD COLUMN IF NOT EXISTS house_tables INTEGER[] NOT NULL DEFAULT '{30,31,32}'::integer[];

COMMENT ON COLUMN slicer_settings.house_tables IS
  'Номера столов-домиков: на карточке заказа такой номер рисуется кирпичным '
  'цветом в рамке в форме домика. Пустой массив = метка выключена. '
  'Правится в UI: Админка → Общие Настройки → «Столы-домики».';

-- Санитарный CHECK. Проверить «все элементы > 0» в CHECK нельзя (потребовался
-- бы unnest/подзапрос), поэтому диапазон номера (1..9999) валидирует API
-- (PUT /api/settings) и UI; в схеме закрепляем то, что выразимо: без NULL
-- внутри массива (NULL сломал бы includes() на фронте) и разумный предел
-- длины — список рассадки, а не свалка.
ALTER TABLE slicer_settings
  DROP CONSTRAINT IF EXISTS slicer_settings_house_tables_sane;
ALTER TABLE slicer_settings
  ADD CONSTRAINT slicer_settings_house_tables_sane
  CHECK (
    COALESCE(array_length(house_tables, 1), 0) <= 100
    AND array_position(house_tables, NULL::integer) IS NULL
  );
